#!/usr/bin/env python3
"""Localize the BTS edge-setting count discrepancy in saved per-shot records.

Probabilities are dimensionless, count discrepancies are particles, and positions
are metres. No tracking is run. Every invocation writes a new output directory.
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
CAMPAIGN = ROOT / 'results/bts_round5_campaign_20261031/final_test_b'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    raw_path, summary_path = CAMPAIGN / 'raw_machines.json', CAMPAIGN / 'final_test.json'
    raw = json.loads(raw_path.read_text())
    summary = json.loads(summary_path.read_text())
    particles = summary['protocol']['particles_per_shot']
    rows = []
    for machine in raw:
        for shot in machine['shots']:
            value = shot['results']['edge_best']['full']
            expected = particles * value['loss_max']
            rows.append({'machine': machine['machine'], 'shot': shot['shot'],
                         'observed': value['lost'], 'expected': expected,
                         'model_union_expected': particles * value['loss_union'],
                         'excess': value['lost'] - expected,
                         'binomial_variance': particles * value['loss_max'] * (1 - value['loss_max']),
                         'exit_centroid_m_rad': value['exit_centroid'],
                         'active': value['active'], 'first_losses': value['first_losses']})
    observed = sum(row['observed'] for row in rows)
    expected = sum(row['expected'] for row in rows)
    stored = summary['validation']['edge_best']
    assert observed == stored['observed_count'] == 942
    np.testing.assert_allclose(expected, stored['conditional_expected_count'], rtol=1e-13)
    worst = max(rows, key=lambda row: row['excess'])
    assert (worst['machine'], worst['shot'], worst['observed']) == (116, 2, 454)
    worst['diagnostic_binomial_z'] = worst['excess'] / np.sqrt(worst['binomial_variance'])
    worst['share_of_aggregate_excess_percent'] = 100 * worst['excess'] / (observed - expected)
    record = {
        'scope': 'Saved-output post-processing; model probabilities do not bound sampled counts.',
        'source_sha256': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                          for p in [raw_path, summary_path, Path(__file__).resolve()]},
        'machines': len(raw), 'shots': len(rows), 'particles_per_shot': particles,
        'loss_bearing_shots': sum(row['observed'] > 0 for row in rows),
        'observed_count': observed, 'conditional_expected_count': expected,
        'model_union_expected_count': sum(row['model_union_expected'] for row in rows),
        'aggregate_excess': observed - expected, 'largest_excess_shot': worst,
        'nonlinear_moment_check': 'Not performed; excess remains unresolved. Binomial z is diagnostic and omits model uncertainty.',
    }
    assert record['loss_bearing_shots'] == 16
    args.output_dir.mkdir(parents=True, exist_ok=False)
    (args.output_dir / 'shot_loss_diagnostic.json').write_text(json.dumps(record, indent=2) + '\n')
    macros = {'LossShots': str(record['loss_bearing_shots']), 'TotalShots': str(record['shots']),
              'WorstLost': str(worst['observed']), 'WorstExpected': f"{worst['expected']:.1f}",
              'ExcessSharePct': f"{worst['share_of_aggregate_excess_percent']:.0f}"}
    text = '% Generated by scripts/audit_bts_round7_shot_losses.py from saved outputs.\n'
    text += ''.join('\\newcommand{\\BtsRSeven' + name + '}{' + value + '}\n' for name, value in macros.items())
    (args.output_dir / 'round7.tex').write_text(text)
    print(json.dumps({key: record[key] for key in ('shots', 'loss_bearing_shots', 'observed_count', 'conditional_expected_count')}))


if __name__ == '__main__':
    main()
